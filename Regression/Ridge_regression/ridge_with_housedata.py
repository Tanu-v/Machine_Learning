import pandas as pd
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression, Ridge

df = pd.read_csv('/content/housinghw.csv')
df

df.shape

df.info()

df.isnull().sum()

df.columns

"""### As the data has no null values we can move further with it without performing any more EDA process

"""

x = df.iloc[:,0:5]
x

y = df.iloc[:,5]
y

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.2,random_state=0)

lr = LinearRegression()
lr.fit(x_train,y_train)
lr.score(x_train,y_train)

"""### alpha = 0.001"""

rr = Ridge(alpha=0.001)
rr.fit(x_test,y_test)
rr.score(x_test,y_test)

"""### Let us check accuracy with a different alpha value
### alpha = 0.01
"""

rr = Ridge(alpha=0.01)
rr.fit(x_test,y_test)
rr.score(x_test,y_test)

"""### alpha = 0.5"""

rr = Ridge(alpha=0.5)
rr.fit(x_test,y_test)
rr.score(x_test,y_test)

rr = Ridge(alpha=0.1)
rr.fit(x_test,y_test)
rr.score(x_test,y_test)

"""### lets move futher with alpha value 0.001 as it gives the highest accuracy!"""

rr = Ridge(alpha=0.001)
rr.fit(x_test,y_test)
rr.score(x_test,y_test)

