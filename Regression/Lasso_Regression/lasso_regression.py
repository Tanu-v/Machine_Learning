import pandas as pd
import matplotlib.pyplot as plt
df = pd.read_csv('/content/housinghw.csv')
df

df.shape

df.info()

df.isnull().sum()

names = df.columns
names

df.drop(["Address"], axis=1, inplace=True)

x = df.drop("Price", axis=1)
x

y = df["Price"].values
y

names = x.columns
names

rng = range(len(names))
rng

from sklearn.linear_model import Lasso
ls = Lasso(alpha=0.1)
ls.fit(x,y)

cf = ls.fit(x,y).coef_
cf

plt.plot(rng, cf)
plt.xticks(rng, names, rotation=60)
plt.ylabel("Coefficients")
plt.show()

ls.fit(x,y).score(x,y)

newdata = [[36000,7,9,5,234000]]

price = ls.fit(x,y).predict(newdata)
price