import pandas as pd
imdb = pd.read_csv('/content/IMDB-Movie-Data.csv')
print(imdb)

imdb.isnull().sum()

imdb.dropna(inplace=True)
imdb

x = imdb.iloc[:,6:10].values
y = imdb.iloc[:,10].values

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.2,random_state=10)

from sklearn.linear_model import LinearRegression
Lnr = LinearRegression()
Lnr.fit(x_train,y_train)

from sklearn.metrics import r2_score
y_pred = Lnr.predict(x_test)
r2_score(y_test,y_pred)

Lnr.score(x_test,y_test)

Lnr.predict([[2050,189,7.6,56332]])

Lnr.predict([[2035,135,9.2,223016],[2046,169,7.4,18093],[2029,153,4.3,26635]])