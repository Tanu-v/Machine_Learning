import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression,Ridge,Lasso,ElasticNet
from sklearn.model_selection import train_test_split

ml = pd.read_csv('/content/diabetes.csv')
ml

ml.shape

ml.info()

ml.isnull().sum()

"""### As there is no null values we can move further with this data and now define x and y"""

x = ml.drop('Outcome',axis=1)
x

y = ml['Outcome'].values
y

"""##Ridge Regression"""

x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.1,random_state=10)

lr = LinearRegression()
lr.fit(x_train,y_train)

lr.score(x_train,y_train)

rr = Ridge(alpha=0.01)
rr.fit(x_test,y_test)

rr.score(x_test,y_test)

rr.predict([[9,123,62,122,113,69.9,1.08,38]])

rr.predict([[14,153,86,91,235,112,0.119,57]])

"""## Lasso Regression"""

names = x.columns
names

rng = range(len(names))
rng

ls = Lasso(alpha=0.1)

data = ls.fit(x,y)

cf = data.coef_
cf

plt.plot(rng,cf)
plt.xticks(rng,names,rotation=60)
plt.ylabel('Coefficients')
plt.show()

data.predict([[9,123,62,122,113,69.9,1.08,38],[14,153,86,91,235,112,0.119,57]])

"""## ElasticNet Regression"""

es = ElasticNet(l1_ratio=0.5)

model = es.fit(x,y)

es_cf = model.coef_
es_cf

n = np.argmax(es_cf)
n

print("The most influencing column=",names[n])

plt.plot(rng,es_cf)
plt.xticks(rng,names,rotation=60)
plt.ylabel('Coefficients')
plt.show()

model.predict([[9,123,62,122,113,69.9,1.08,38],[14,153,86,91,235,112,0.119,57]])