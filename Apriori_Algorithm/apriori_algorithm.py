import pandas as pd
df = open('/content/store_data.csv', 'r')

fe = []
for i in df:
  line = i.split(',')
  fe.append(line)

fe[:5]

"""# Now we're going to create our apriori algorithm model

---



---


"""

from apyori import apriori
result = apriori(fe, min_support=0.003, min_confidence=0.2, min_lift=3, min_length=2)
result = list(result)
print(result)

for relation_record in result:
    for ordered_stat in relation_record.ordered_statistics:
        if ordered_stat.lift >= 7:
            print(f"Items: {relation_record.items}, Support: {relation_record.support}, Confidence: {ordered_stat.confidence}, Lift: {ordered_stat.lift}\n")

for relation_record in result:
    items = [item for item in relation_record.items]
    print("Items: " + ", ".join(items))
    print("Support: " + str(relation_record.support))
    for ordered_stat in relation_record.ordered_statistics:
        print("Confidence: " + str(ordered_stat.confidence))
        print("Lift: " + str(ordered_stat.lift))
    print("\n") # Add a newline for better readability between rules