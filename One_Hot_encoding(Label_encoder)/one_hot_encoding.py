df

from sklearn.preprocessing import OneHotEncoder
Ohe = OneHotEncoder(handle_unknown='ignore')
df1 = Ohe.fit_transform(df[['mainroad']])
df2 = Ohe.fit_transform(df[['furnishingstatus']])
df1 = pd.DataFrame(df1.toarray())
print(df1)
df2 = pd.DataFrame(df2.toarray())
print(df2)

df1 = df1.iloc[:,1:]
print(df1)
df2 = df2.iloc[:,1:]
print(df2)

x1 = df[['area', 'bedrooms', 'bathrooms', 'stories', 'mainroad', 'furnishingstatus']]
x2 = pd.concat([x1, df1,df2], axis='columns')
print(x2)
x2.columns = x2.columns.astype(str)
print(x2)
x = x2.drop(['mainroad','furnishingstatus'],axis=1)
print(x)

from sklearn.linear_model import LinearRegression
model = LinearRegression()
model.fit(x,y)

model.predict([[2800,2,2,1,0,0,1]])

from sklearn.metrics import r2_score
y_pred = model.predict(x)
r2_score(y,y_pred)

