import pandas as pd
colnames = ['age','sex','cp','trestbps','chol','fbs','restecg','thalach','exang','oldpeak','slope','ca','thal','num']
df = pd.read_csv("/content/processed.cleveland.data" , sep=',', names=colnames)
df

df['num'] = df.num.map({0: 0 , 1: 1 , 2: 1 , 3: 1 , 4: 1})
x = df.drop('num', axis=1)
y = df['num']

from sklearn.model_selection import train_test_split
x_train, x_test, y_train, y_test = train_test_split(x, y ,test_size = 0.3, random_state=0)

from sklearn.preprocessing import StandardScaler
from sklearn.impute import SimpleImputer
import numpy as np
import pandas as pd

# Identify columns with '?' based on initial df inspection (ca, thal)
cols_to_clean = ['ca', 'thal']

# Replace '?' with NaN in x_train and x_test for identified columns
for col in cols_to_clean:
    if col in x_train.columns:
        x_train[col] = x_train[col].replace('?', np.nan)
        x_test[col] = x_test[col].replace('?', np.nan)

# Convert any remaining object columns to numeric (coercing errors to NaN)
# This handles cases where other columns might have '?' or other non-numeric strings
for col in x_train.columns:
    if x_train[col].dtype == 'object':
        x_train[col] = pd.to_numeric(x_train[col], errors='coerce')
    if x_test[col].dtype == 'object':
        x_test[col] = pd.to_numeric(x_test[col], errors='coerce')

# Impute missing values (NaN) using the mean strategy
imputer = SimpleImputer(strategy='mean')

# Fit imputer on x_train and transform both x_train and x_test
x_train_imputed = imputer.fit_transform(x_train)
x_test_imputed = imputer.transform(x_test)

# Now, apply StandardScaler to the imputed (and fully numeric) data
sc = StandardScaler()
x_train1 = sc.fit_transform(x_train_imputed)
x_test1 = sc.transform(x_test_imputed)

from sklearn.svm import SVC
m1 = SVC(kernel='rbf')
m1.fit(x_train1, y_train)
ts1= m1.score(x_test1, y_test)
trs1 = m1.score(x_train1, y_train)
print("score on train data= %.2f" % trs1)
print("score on test data= %.2f" % ts1)

from sklearn.naive_bayes import GaussianNB
m2 = GaussianNB()
m2.fit(x_train1, y_train)
ts2= m2.score(x_test1, y_test)
trs2 = m2.score(x_train1, y_train)
print("score on train data= %.2f" % trs2)
print("score on test data= %.2f" % ts2)

from sklearn.linear_model import LogisticRegression
m3 = LogisticRegression()
m3.fit(x_train1, y_train)
ts3 =m3.score(x_test1, y_test)
trs3 = m3.score(x_train1, y_train)
print("score on train data= %.2f" % trs3)
print("score on test data= %.2f" % ts3)

from sklearn.tree import DecisionTreeClassifier
m4 = DecisionTreeClassifier()
m4.fit(x_train1, y_train)
ts4= m4.score(x_test1, y_test)
trs4 = m4.score(x_train1, y_train)
print("score on train data= %.2f" % trs4)
print("score on test data= %.2f" % ts4)

from sklearn.ensemble import RandomForestClassifier
m5 = RandomForestClassifier()
m5.fit(x_train1, y_train)
ts5= m5.score(x_test1, y_test)
trs5 = m5.score(x_train1, y_train)
print("score on train data= %.2f" % trs5)
print("score on test data= %.2f" % ts5)

