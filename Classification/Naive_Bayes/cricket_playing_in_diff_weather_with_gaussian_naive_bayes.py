import pandas as pd
nbd = pd.read_csv('/content/Cricket.csv')
nbd

nbd.info()

nbd.head()

nbd.tail()

nbd.isnull()

def outlook_to_numeric(x):
  if x=='Sunny':
    return 0
  if x=='Overcast':
    return 1
  if x=='Rainy':
    return 2
  if x=='Outcast':
    return 3

def temperature_to_numeric(x):
  if x=='Hot':
    return 0
  if x=='Mild':
    return 1
  if x=='Cool':
    return 2

def humidity_to_numeric(x):
  if x=='High':
    return 0
  if x=='Normal':
    return 1

def windy_to_numeric(x):
  if x==False:
    return 0
  if x==True:
    return 1

def playcricket_to_numeric(x):
  if x=='No':
    return 0
  if x=='Yes':
    return 1

nbd['OUTLOOK'] = nbd['OUTLOOK'].apply(outlook_to_numeric)

nbd['TEMPERATURE'] = nbd['TEMPERATURE'].apply(temperature_to_numeric)

nbd['HUMIDITY'] = nbd['HUMIDITY'].apply(humidity_to_numeric)

nbd['WINDY'] = nbd['WINDY'].apply(windy_to_numeric)

nbd['PLAY CRICKET'] = nbd['PLAY CRICKET'].apply(playcricket_to_numeric)

x = nbd[['OUTLOOK','TEMPERATURE','HUMIDITY','WINDY']]
y = nbd['PLAY CRICKET']

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.3,random_state=10)

from sklearn.naive_bayes import GaussianNB
gnb = GaussianNB()
gnb.fit(x_train,y_train)

print(x_train.isnull().sum())
print(x_test.isnull().sum())

y_pred = gnb.predict(x_test)

from sklearn import metrics
score = metrics.accuracy_score(y_test,y_pred)
print(score)

gnb.score(x_test , y_test)

