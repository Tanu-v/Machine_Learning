mdf.loc[mdf['v1']=='spam','v1']=1
mdf.head()

x = mdf['v2']
print(x.head())
y = mdf['v1']
print(y.head())

"""## Trainnig the model for Multinomial Naive Bayes Classifier

---



---


"""

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test = train_test_split(x,y,test_size=0.2)

from sklearn.feature_extraction.text import CountVectorizer
cv = CountVectorizer()
x_trainc = cv.fit_transform(x_train)
x_testc = cv.transform(x_test)

y_train = y_train.astype('int')
y_test = y_test.astype('int')

from sklearn.naive_bayes import MultinomialNB
mnb = MultinomialNB()
mnb.fit(x_trainc,y_train)

from sklearn import metrics
score = mnb.score(x_testc,y_test)
print(score)

"""

* Till now we have train our model perfectly .



* Now we'll test our model on the basis of some data we provide .
* Let's see if our model is perfectly working or not .....

"""

exm1 = ['Free viagra now','Hi can we meet tomorrow?']
exm = cv.transform(exm1)
mnb.predict(exm)

