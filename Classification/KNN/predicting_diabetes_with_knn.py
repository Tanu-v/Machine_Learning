from sklearn.neighbors import KNeighborsClassifier
import numpy as np
import pandas as pd
df = pd.read_csv('/content/diabetes.csv')
df

col_list = ['Glucose',  'BloodPressure',        'SkinThickness',        'Insulin',      'BMI']
for i in col_list:
  df[i] = df[i].replace(0, np.nan)
  mean = int(df[i].mean(skipna=True))
  df[i] = df[i].replace(np.nan, mean)
  df.head()

df.tail(20)

x = df.iloc[:,:8]
x

y = df.iloc[:,8]
y

from sklearn.model_selection import train_test_split
x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.2, random_state=0)

import math
k = math.sqrt(len(x_test))
k

kin = int(k)
if kin%2==0:
   kin+=1
   print(kin)

knn = KNeighborsClassifier(n_neighbors=kin)
knn.fit(x_train, y_train)

accuracy = knn.score(x_test, y_test)
accuracy

k_range = range(1,20)
scores = []
for k in k_range:
  knn = KNeighborsClassifier(n_neighbors=k)
  knn.fit(x_train, y_train)
  accuracy = knn.score(x_test, y_test)
  scores.append(accuracy)
  print('k = %d Accuracy = %.2f%%' %(k, accuracy*100))

import matplotlib.pyplot as plt
plt.plot(k_range, scores)
plt.xlabel('Value of K for KNN')
plt.ylabel('Testing Accuracy')
plt.show()

knn = KNeighborsClassifier(n_neighbors=14 , metric = 'euclidean')
knn.fit(x_train, y_train)

accuracy = knn.score(x_test, y_test)
accuracy

