import pandas as pd
import numpy as np
import seaborn as sns

from sklearn import datasets
iris = datasets.load_iris()
iris.data

iris.feature_names

x = pd.DataFrame(iris.data, columns=iris.feature_names)
x

y = iris.target
y

from sklearn.preprocessing import StandardScaler
scaler = StandardScaler()
x_scaled = scaler.fit_transform(x)
x_scaled

rows = x_scaled.T
covariance_matrix = np.cov(rows)
covariance_matrix

eig_vals,eig_vecs = np.linalg.eig(covariance_matrix)
print('Eigenvectors \n%s' %eig_vecs)
print('\nEigenvalues \n%s' %eig_vals)

for i in range (len(eig_vals)):
    print(eig_vals[i]/sum(eig_vals))

pc1 = x_scaled.dot(eig_vecs.T[0])
pc2 = x_scaled.dot(eig_vecs.T[1])

df = pd.DataFrame(pc1 ,columns=['PC1'])
df['PC2'] = pc2
df['target']= y
df

sns.lmplot(x='PC1',y='PC2',data=df,hue='target',fit_reg=False)

from sklearn.decomposition import PCA
pca = PCA(n_components=2)
projected_data = pca.fit_transform(x_scaled)

pc1 = projected_data[:,0]
pc2 = projected_data[:,1]

df1 = pd.DataFrame(pc1 ,columns=['PC1'])
df1['PC2'] = pc2
df1['target']= y
df1

sns.lmplot(x='PC1',y='PC2',data=df1,hue='target',fit_reg=False)

df1= df1.drop('target', axis=1)
df1

from sklearn.model_selection import train_test_split
x_train, x_test, y_train, y_test = train_test_split(df1, y, test_size=0.2)

from sklearn.svm import SVC
model = SVC()
model.fit(x_train, y_train)

model.score(x_test, y_test)

inputs= np.array([[6.6,3.0,4.4,1.4]])

scaled = scaler.fit_transform(inputs)

"""## Here in this section we did not use fit_transform we only used pca.transform"""

