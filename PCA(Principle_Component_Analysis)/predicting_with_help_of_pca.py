import pandas as pd
import numpy as np
import seaborn as sns

from sklearn import datasets
iris = datasets.load_iris()
iris.data

iris.feature_names

x = pd.DataFrame(iris.data, columns=iris.feature_names)
x

y = iris.target
y

from sklearn.preprocessing import StandardScaler
scaler = StandardScaler()
x_scaled = scaler.fit_transform(x)
x_scaled

rows = x_scaled.T
covariance_matrix = np.cov(rows)
covariance_matrix

eig_vals,eig_vecs = np.linalg.eig(covariance_matrix)
print('Eigenvectors \n%s' %eig_vecs)
print('\nEigenvalues \n%s' %eig_vals)

for i in range (len(eig_vals)):
    print(eig_vals[i]/sum(eig_vals))

projected_x = x_scaled.dot(eig_vecs.T[0])
projected_x

df = pd.DataFrame(projected_x, columns=['PC1'])
df['y-axis'] = 0.0
df['target'] = y
df

sns.lmplot(x='PC1', y='y-axis', data=df, fit_reg=False, hue="target")

from sklearn.decomposition import PCA
pca = PCA(n_components=1)
projected_x = pca.fit_transform(x_scaled)

df1 = pd.DataFrame(projected_x, columns=['PC1'])
df1['y-axis'] = 0.0
df1['target'] = y
df1

sns.lmplot(x='PC1', y='y-axis', data=df1, fit_reg=False, hue="target")

print(x_scaled.shape)
print(projected_x.shape)

data= projected_x.reshape(-1,1)

from sklearn.model_selection import train_test_split
x_train, x_test, y_train, y_test = train_test_split(data, y, test_size=0.2)

from sklearn.svm import SVC
model = SVC()
model.fit(x_train, y_train)

model.score(x_test, y_test)

inputs= np.array([[6.6,3.0,4.4,1.4]])

scaled = scaler.fit_transform(inputs)

pca_inputs = pca.fit_transform(scaled)

model.predict(pca_inputs)