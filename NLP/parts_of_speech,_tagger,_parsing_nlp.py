import nltk
nltk.download('punkt_tab')
nltk.download('averaged_perceptron_tagger_eng')

from nltk import word_tokenize
w = "Let's do it today and not make any mistake for further corrections."
print(nltk.pos_tag(word_tokenize(w)))

w1 = "kertoenova"
print(nltk.pos_tag(word_tokenize(w1)))

"""#default tagger"""

from nltk.tag import DefaultTagger
dt = DefaultTagger('VB')
print(dt.tag(word_tokenize(w1)))

dt1 = DefaultTagger('DT')
dt1.tag(['I','am','rude','girl','.'])

"""#Untagging

"""

from nltk.tag import untag
o = untag([('I', 'PRP'), ('am', 'VB'), ('rude', 'JJ'), ('girl', 'NN'), ('.', '.')])
o

nltk.pos_tag(o) #tagging after untagging and the input is already tokenized

