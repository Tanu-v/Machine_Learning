import pandas as pd
df = pd.read_csv('/content/processed_aqi.csv')
df.head()

"""#1.Mean"""

mean = df['AQI'].mean()
print(mean)

"""#2.Median"""

median = df['AQI'].median()
print(median)

"""#3.Mode"""

from scipy import stats
mode = stats.mode(df['AQI'])
print(mode)

"""#4.Standard deviation"""

std_dev = df['AQI'].std()
print(std_dev)

"""#5.Variance"""

variance=df['AQI'].var()
print(variance)

"""#6.Minimum"""

min_value=df['AQI'].min()
print(min_value)

"""#7.Maximum"""

max_value=df['AQI'].max()
print(max_value)

"""#8.Percentile"""

percentile = df['AQI'].quantile(0.9)
print(percentile)

"""#9.Kurtosis"""

from scipy.stats import kurtosis
kurtosis_value = kurtosis(df['AQI'])
print(kurtosis_value)

"""#10.Skewness"""

from scipy.stats import skew
skewness_value = skew(df['AQI'])
print(skewness_value)

"""#11.Correlation"""

correlation=df['AQI'].corr(df['PM2.5'])
print(correlation)

import seaborn as sns
sns.pairplot(df)